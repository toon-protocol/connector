//! The committed `local/*/*.toml` files load, and say what the compose file,
//! the chain seeding and `local/keys.sh` beside them assume they say.
//!
//! `local/`'s configs are committed rather than generated, for the reason ADR
//! 0009 gives: a config nobody reads is a config nobody reviews. The cost of
//! that choice is drift -- a renamed compose service, a moved mount path, or a
//! settlement address that quietly stops matching what the chain actually
//! holds, none of which the TOML alone can notice. `devnet_configs_load.rs`
//! holds the fleet configs to exactly this standard; these are the local ones,
//! and they are cheaper to check because everything they name is
//! deterministic.
//!
//! **Every channel is an x402 channel, and no local config names one** (ADR
//! 0075, issue #1383). A peering is two one-way `batch-settlement` channels,
//! each opened by its own payer, and it is established from a URL by a signed
//! `POST /peers` on each end (ADR 0058 as 0075 decision 4 amends it) -- so no
//! committed file here holds a `[[peers]]`, `[[peer_channels]]` or
//! `[[pay_channels]]` row. What each peering costs lives in `local/keys.sh`'s
//! topology table instead (its `fee`, its cap, and the forwarding route's
//! `price`), because that script makes the writes. So the multi-file drift this
//! test has always caught -- a figure that must agree across two or three
//! files, and fails at run time as a refused or short payment rather than as a
//! refused config -- now spans the configs, that table and the rehearsal, and
//! [`topology`] is how this file reads the table.
//!
//! What is substituted, and only this: the key files (real key material is
//! never committed -- `local/keys.sh` writes it into a gitignored directory at
//! run time), `state_dir` and `client_edge_addr` (container paths and fixed
//! ports that no test host can supply). Every other line is the literal
//! committed content.

