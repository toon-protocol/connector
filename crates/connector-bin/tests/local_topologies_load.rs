/// The one service block `local/onion/compose.yml` declares under `service`.
///
/// Read as text, like every other compose assertion in this file, but per
/// SERVICE rather than per file: this topology's whole claim is about which
/// container is on which network, and `ONION_COMPOSE.contains("onion-a")`
/// would be satisfied by any service naming it. A block ends at the next line
/// that is not indented into it.
fn onion_service(service: &str) -> &'static str {
    let head = format!("\n  {service}:\n");
    let start = ONION_COMPOSE
        .find(&head)
        .unwrap_or_else(|| panic!("local/onion/compose.yml declares no `{service}` service"))
        + head.len();
    let body = &ONION_COMPOSE[start..];
    let mut end = body.len();
    let mut offset = 0;
    for line in body.lines() {
        if !line.is_empty() && !line.starts_with("    ") {
            end = offset;
            break;
        }
        offset += line.len() + 1;
    }
    &body[..end]
}

/// The placeholder the committed configs carry where the daemon's address
/// goes, and the reason a placeholder is legitimate here at all: it still
/// ends in a hidden-service suffix, so the committed files load through the
/// real parser and mean something to every other test in this file.
///
/// `.anyone` rather than `.onion` because that is the TLD the daemon this
/// topology builds actually writes (issue #1284) -- held to the image pin by
/// [`the_onion_sidecar_is_the_daemon_that_writes_the_placeholders_tld`].
const ONION_PLACEHOLDER: &str = "placeholderplaceholderplaceholderplaceholderplaceholderb.anyone";

#[test]
fn the_onion_topologys_committed_configs_load() {
    let payer = load("local/onion/connector-a.toml", ONION_A);
    let payee = load("local/onion/connector-b.toml", ONION_B);

    assert!(
        payer.routes().is_empty(),
        "A must terminate NOTHING -- a locally terminated route would give a fulfilled packet a \
         second possible explanation, and this topology's whole point is that it has exactly one"
    );
    assert_eq!(payer.peer_routes().len(), 1);
    let forward = &payer.peer_routes()[0];
    assert_eq!(forward.prefix(), "g.local.onion.b");
    assert_eq!(forward.peer_id(), "a-b");
    assert_eq!(payee.routes().len(), 1);
    assert_eq!(payee.routes()[0].prefix(), "g.local.onion.b.app");
    assert!(
        payee.routes()[0].prefix().starts_with(forward.prefix()),
        "the app's address must sit UNDER the prefix A forwards, or longest-prefix matching \
         sends the packet somewhere else entirely"
    );

    // ADR 0028's arithmetic, held here because nothing in the code holds it:
    // a hop collects `price`, forwards `price - fee`, and earns exactly its
    // fee. Equality rather than `>=`, for `two-hop`'s reason -- slack is
    // indistinguishable from a discount.
    let fee = fee_of(&payer, forward);
    assert!(
        fee > 0,
        "THE HOP MUST CHARGE. A peering carried over a circuit is priced like any other (ADR \
         0010, ADR 0061), and a fee quietly back at zero is a rehearsal that carries for free -- \
         which B's journal reads exactly as green either way."
    );
    assert_eq!(
        flat(forward.price()) - fee,
        flat(payee.routes()[0].price()),
        "A collects {} and retains {}, so it forwards {} -- and B's route costs {}",
        flat(forward.price()),
        fee,
        flat(forward.price()) - fee,
        flat(payee.routes()[0].price())
    );
    assert_ne!(
        (flat(forward.price()), fee),
        (1100, 100),
        "these are `two-hop`'s figures. A fee is one peering relation's bilateral price for \
         carriage, never a network-wide constant, and two topologies sharing one set of numbers \
         is how a config copied wholesale from the other passes unnoticed."
    );

    for (name, config) in [("A", &payer), ("B", &payee)] {
        assert_eq!(
            config.settlements().len(),
            1,
            "{name} settles on EVM alone in this topology"
        );
        assert_eq!(config.settlements()[0].chain(), SettlementChain::Evm);
    }
    assert!(
        payer.operator().is_some(),
        "the rehearsal originates its packet through A's `POST /packets`"
    );
    assert!(
        payee.operator().is_none(),
        "CF-31: B is never sent to directly, and an unused authenticated surface behind an onion \
         address is still an unused authenticated surface"
    );
}

/// **The host is the only thing that changed** (ADR 0070).
///
/// A `.onion` endpoint adds no third carriage: `ws://` selects BTP at an
/// onion host exactly as it does at a DNS one, and the peering's row is
/// otherwise indistinguishable from `mixed-chain`'s. This is the assertion
/// that would fail if a `PeerCarriage::Onion` were ever introduced -- the
/// record's own falsifier, read off a config that loads.
#[test]
fn the_onion_peering_is_an_ordinary_btp_peering_at_an_extraordinary_host() {
    let payer = load("local/onion/connector-a.toml", ONION_A);
    let payee = load("local/onion/connector-b.toml", ONION_B);

    let endpoint = payer.peers()[0]
        .endpoint()
        .expect("A dials, so A's row carries the endpoint");
    assert!(
        connector_config::is_onion_endpoint(endpoint),
        "A's peer endpoint must be an onion one ({endpoint}), or this topology is `two-hop` with \
         a sidecar attached"
    );
    assert_eq!(
        payer.peers()[0].dial(),
        Some(connector_config::PeerCarriage::Btp),
        "`ws://` selects BTP, and the host takes no part in that choice. BTP deliberately: the \
         HTTP carriage asks its client for a proxy, while the websocket library this one speaks \
         has none at all and its onion path hands an already-established SOCKS5 stream to the \
         websocket client (issue #1277). That is the change a loopback fake can least stand in \
         for, so it is the one pointed at a real daemon."
    );
    assert_eq!(
        payee.peer_expose(),
        connector_config::PeerExposure::Btp,
        "B accepts A over BTP and mounts NO ILP-over-HTTP peer carriage. That absence is what \
         makes an accepted peer claim in B's journal evidence of the carriage: an A that had \
         somehow arrived on `POST /ilp` would be admitted as an ordinary client, whose claims \
         never reach the peer book."
    );
    assert!(
        payee.peers()[0].endpoint().is_none(),
        "B dials nothing -- it is reachable, not reaching"
    );

    // Decision 3: one proxy, named once, and selected per endpoint by host.
    let proxy = payer
        .socks_proxy()
        .expect("A dials an onion peer, so A configures the proxy to dial it through");
    assert_eq!(
        proxy.scheme(),
        "socks5h",
        "the `h` is not a preference: no resolver on that container can resolve a `.onion` name, \
         so resolution has to happen AT the proxy (ADR 0070 decision 3)"
    );
    assert_eq!(
        proxy.host_str(),
        Some("anon-a"),
        "the proxy must name the sidecar on A's own network -- it is the only thing on that \
         network with a way onto the onion network at all"
    );
    for (name, config) in [
        ("local/solo/connector.toml", SOLO_CONFIG),
        ("local/two-hop/connector-a.toml", TWO_HOP_A),
        ("local/mixed-chain/connector-a.toml", MIXED_A),
        ("local/onion/connector-b.toml", ONION_B),
    ] {
        assert!(
            load(name, config).socks_proxy().is_none(),
            "{name} must configure no proxy: a node that dials no onion endpoint dials \
             everything direct, and `socks_proxy` is not a mode that reroutes a node's traffic"
        );
    }

    // Decision 2, measured rather than restated. `plaintext_peerings` is what
    // the startup WARN names, and it excludes an onion endpoint on purpose: a
    // v3 onion address IS the key the circuit authenticates to, so ADR 0004's
    // requirement is satisfied by another mechanism rather than waived.
    assert_eq!(
        payer.plaintext_peerings().count(),
        0,
        "a `ws://…onion` peering must not be warned about as an unauthenticated one"
    );

    // And the whole node takes the opt-in nowhere. This is the assertion that
    // says ADR 0070's exemption is a real one rather than a label on the old
    // switch: A holds three plaintext URLs at onion hosts -- the peering's
    // `endpoint`, the `[[pay_channels]]` row's `client_edge_url`, and the
    // `.onion` a runtime peering would be established from -- and loads with
    // `peer_allow_plaintext_endpoints` absent. A node that needed it would be
    // opening plaintext to EVERY peer in order to get it for one, which is the
    // deployment shape that switch's own doc comment refuses and the reason
    // decision 2 keyed the rule on the host suffix instead.
    for (name, config, loaded) in [
        ("local/onion/connector-a.toml", ONION_A, &payer),
        ("local/onion/connector-b.toml", ONION_B, &payee),
    ] {
        assert!(
            !loaded.peer_allow_plaintext_endpoints(),
            "{name} must load without the plaintext opt-in -- an onion node needing it would \
             mean ADR 0070's exemption had not actually been implemented"
        );
        assert!(
            !config.contains("peer_allow_plaintext_endpoints = true"),
            "{name} must not write the opt-in either, even inertly: a copied config carries \
             the line, and this one is read as the example of what an onion node needs"
        );
    }
}

