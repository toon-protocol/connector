/// The shape nothing else in this repository covers: one node holding two
/// settlement backends with a peering on each, so a packet crosses a chain
/// boundary between two hops.
///
/// Not a conversion, and this test is written so it could not be mistaken for
/// one: the only thing that changes an amount between two hops here is a hop
/// subtracting its own FLAT fee (issue #1144), so every gap on the path is a
/// fixed number of base units rather than a share of what arrived. What has
/// changed is *why*. Conversion is no longer somebody else's repository: ADR
/// 0071 made crossing a denomination core forwarding behaviour, and the chain
/// boundary in B's middle is exactly the place it would happen. What holds
/// these figures still is that record's decision 2 -- no declared rate, no
/// conversion, no forward. None of these three files declares a `[[tokens]]`
/// row, so B resolves no token for either peering, sits on no denomination
/// boundary at all, and runs the unconverted forward byte for byte as it did
/// before 0071. A node that DID declare tokens would be held to the absence
/// rule on this very pair -- USDC on anvil and USDC on the test validator are
/// two `AssetId`s, and an `AssetId` is chain-qualified -- and would have to
/// declare that pair at par, in as many words, before it forwarded anything
/// across it.
#[test]
fn the_mixed_chain_topology_puts_one_node_on_both_chains() {
    let a = load("local/mixed-chain/connector-a.toml", MIXED_A);
    let b = load("local/mixed-chain/connector-b.toml", MIXED_B);
    let c = load("local/mixed-chain/connector-c.toml", MIXED_C);

    assert_eq!(
        a.settlements().len(),
        1,
        "A settles on EVM alone and cannot verify a Solana claim"
    );
    assert_eq!(a.settlements()[0].chain(), SettlementChain::Evm);
    assert_eq!(
        c.settlements().len(),
        1,
        "C settles on Solana alone and cannot verify an EIP-712 balance proof -- which is what \
         makes a packet arriving there evidence of a real chain boundary rather than of one \
         chain with two config shapes"
    );
    assert_eq!(c.settlements()[0].chain(), SettlementChain::Solana);

    let mut chains: Vec<SettlementChain> = b.settlements().iter().map(|s| s.chain()).collect();
    chains.sort_by_key(|chain| format!("{chain:?}"));
    assert_eq!(
        chains,
        vec![SettlementChain::Evm, SettlementChain::Solana],
        "B is the boundary: it holds BOTH backends, and a peering can only be signed for on a \
         chain whose settlement key this node has"
    );

    assert_eq!(
        evm_channel(&b, "a-b").chain_id(),
        31_337,
        "the EVM half of the boundary is judged under anvil's own chain id"
    );
    assert_eq!(
        solana_channel(&b, "b-c").program_id(),
        LOCAL_TEST_PROGRAM_ID,
        "the Solana half names the deployed program, which ADR 0053 binds into the signed \
         message -- a claim rendered under another deployment does not verify"
    );
}

/// The path's routing and its arithmetic, which are the same fact read two
/// ways: each hop's prefix is a prefix of the next hop's, and each hop's
/// `price` is the next hop's `price` plus its own `fee`. Both are held here
/// because both live in three files at once and neither is checked anywhere
/// at run time -- a route that stops nesting sends the packet somewhere else
/// entirely, and a price that stops adding up sends value nobody charged for.
#[test]
fn the_mixed_chain_path_is_one_prefix_per_hop_and_one_flat_fee_per_hop() {
    let a = load("local/mixed-chain/connector-a.toml", MIXED_A);
    let b = load("local/mixed-chain/connector-b.toml", MIXED_B);
    let c = load("local/mixed-chain/connector-c.toml", MIXED_C);

    assert!(a.routes().is_empty(), "A terminates nothing");
    assert!(b.routes().is_empty(), "B terminates nothing -- it is a hop");
    assert_eq!(a.peer_routes().len(), 1);
    assert_eq!(b.peer_routes().len(), 1);
    assert_eq!(c.peer_routes().len(), 0);
    assert_eq!(c.routes().len(), 1);

    let first = &a.peer_routes()[0];
    let second = &b.peer_routes()[0];
    let app = &c.routes()[0];
    assert_eq!(first.prefix(), "g.local.mixed.b");
    assert_eq!(second.prefix(), "g.local.mixed.b.c");
    assert_eq!(app.prefix(), "g.local.mixed.b.c.app");
    assert!(
        second.prefix().starts_with(first.prefix()) && app.prefix().starts_with(second.prefix()),
        "each hop's route must be a prefix of the next, or longest-prefix matching sends the \
         packet off the path this topology describes"
    );

    // EVERY FORWARDING HOP CHARGES (issue #1144), and the two figures differ.
    // A fee buys carriage over ONE peering relation and is bilateral
    // configuration (ADR 0010), never a network-wide constant -- and two
    // identical fees on a three-node path cannot tell a hop charging its own
    // from a hop charging the one it was handed.
    let first_fee = fee_of(&a, first);
    let second_fee = fee_of(&b, second);
    assert!(
        first_fee > 0 && second_fee > 0,
        "both hops must retain something, or the flat per-packet fee is exercised by no shipped \
         image on this path either. `mixed-chain`'s B is also the only node in this repository \
         that charges a fee on a PEER arrival rather than on an operator-originated packet."
    );
    assert_ne!(
        first_fee, second_fee,
        "the two fees are deliberately different figures: a fee is one peering relation's \
         bilateral price for carriage, and equal fees would let a hop charging the wrong one \
         pass unnoticed"
    );
    assert_eq!(
        flat(first.price()) - first_fee,
        flat(second.price()),
        "STILL NOT A CONVERSION. What leaves A is what arrived minus A's own FLAT fee, and that \
         is exactly B's price -- the whole difference between the two figures is one hop's fee \
         and nothing else. Any other gap would be a rate, and what forbids one here is ADR \
         0071's absence rule (decision 2): these configs declare no tokens, so no hop on this \
         path resolves a denomination to convert between, and a pair nobody declared refuses \
         rather than guesses. The chain boundary in the middle is still exactly where somebody \
         would be tempted to put a rate -- the difference is that they would now have to write \
         one down."
    );
    assert!(
        flat(second.price()) - second_fee >= flat(app.price()),
        "ADR 0028's path invariant, which no code enforces because a connector cannot know what \
         the next hop charges: every hop's `price - fee` must be at least the next hop's price. \
         Here the slack is deliberate and is the value delivered to C's unpriced termination -- \
         what a hop at the end of an unpriced peer termination is actually paid is the \
         forwarded amount."
    );
    assert_eq!(
        flat(app.price()),
        0,
        "C's termination is unpriced BY CHOICE since issue #1145, not by constraint. It used to \
         be forced: the b-c peering was postpay, a priced peer termination refuses an uncovered \
         arrival (F06, issue #880), and a postpay peering's first crossing is uncovered by \
         construction (ADR 0004) -- so a price here deadlocked the leg rather than charging for \
         it. B holds a `[[pay_channels]]` row now and covers before it sends, so a price would \
         be payable. Pricing a peer termination is what two-hop is for; this topology is about \
         one node holding a backend on each of two chains."
    );
}

/// **Both legs are prepay, and neither has a choice about it** (ADR 0042,
/// issue #1145).
///
/// A peering a `[[routes]]` entry forwards to must name the channel it pays
/// that hop from -- `ConfigError::PayChannelUnbound` refuses the file
/// otherwise -- so the two rows below are not decoration a future edit could
/// drop. What this test adds beyond "it loaded" is that each row names the
/// channel its own peering already binds, on the chain that peering settles
/// on: one on-chain channel in two roles with one hop, which is the shape
/// `local/keys.sh` opens and funds exactly one of per peering.
///
/// It is also what makes B's `forwarded_claim_enforcement` safe, which is
/// asserted in `the_mixed_chain_forwarded_arrival_is_enforced` below.
#[test]
fn the_mixed_chain_covers_both_legs_before_it_sends_them() {
    let a = load("local/mixed-chain/connector-a.toml", MIXED_A);
    let b = load("local/mixed-chain/connector-b.toml", MIXED_B);
    let c = load("local/mixed-chain/connector-c.toml", MIXED_C);

    // A -> B, on anvil.
    assert_eq!(a.pay_channels().len(), 1);
    let PayChannelConfig::Evm(a_pays) = &a.pay_channels()[0] else {
        panic!("the a-b leg settles on anvil, so A's row is EVM-shaped");
    };
    let a_peer = evm_channel(&a, "a-b");
    assert_eq!(a_pays.peer_id(), "a-b");
    assert_eq!(
        a_pays.channel_id(),
        a_peer.channel_id(),
        "one on-chain channel in both roles with one hop -- and `local/keys.sh` opens and funds \
         exactly one channel for this peering, so a second id here would be a channel nobody \
         collateralised"
    );
    assert_eq!(a_pays.chain_id(), a_peer.chain_id());
    assert_eq!(
        a_pays.token_network(),
        a_peer.token_network(),
        "both roles sign against the same on-chain channel, so the EIP-712 domain cannot differ \
         -- a claim under the wrong `verifyingContract` recovers to another address entirely"
    );
    // The claim-state ask goes to B's own `POST /ilp`, and since issue #1155
    // it is provably NOT the URL this peering dials: `a-b` is a `ws://`
    // peering. `pay_channel.rs` has always refused to derive one from the
    // other -- "on a `wss://` peering there is no HTTP URL there at all, and
    // turning one into the other by swapping scheme and appending a path is
    // exactly the class of guess ADR 0030 refuses for `btpEndpoint`" -- but
    // until this peering moved to BTP the two were the same string in every
    // committed config, which is the state in which a derivation looks free.
    // This is the assertion in its place, and it is the stronger one.
    assert_ne!(
        Some(a_pays.client_edge_url()),
        a.peers()[0].endpoint(),
        "the two URLs must differ, or this topology has stopped being the place the separation \
         is demonstrated rather than merely documented"
    );
    assert_eq!(
        a_pays.client_edge_url().scheme(),
        "http",
        "the claim-state ask is an HTTP POST whatever carriage the peering rides -- there is no \
         BTP spelling of `POST /ilp/claim-state`"
    );
    assert_eq!(
        a_pays.client_edge_url().host_str(),
        a.peers()[0]
            .endpoint()
            .expect("A dials, so A's row carries the endpoint")
            .host_str(),
        "same node, two wires: the peering's websocket and the claim-state ask must reach the \
         SAME connector, or A is asking one node where its claims against another stand"
    );

    // B -> C, on the Solana validator. A different SHAPE, not a different
    // spelling: this row could not be written at all before issue #1146.
    assert_eq!(b.pay_channels().len(), 1);
    let PayChannelConfig::Solana(b_pays) = &b.pay_channels()[0] else {
        panic!("the b-c leg settles on Solana, so B's row is Solana-shaped");
    };
    let b_peer = solana_channel(&b, "b-c");
    assert_eq!(b_pays.peer_id(), "b-c");
    assert_eq!(
        b_pays.channel_account(),
        b_peer.channel_account(),
        "`ConfigError::PayChannelSolanaWithoutPeerChannel` requires this and it is not a \
         formality: `programId` is a REQUIRED field of the Solana claim wire, rendered from the \
         peer-channel row, so a pay row without one mints claims that cannot be put on the wire"
    );
    let b_to_c = b
        .peers()
        .iter()
        .find(|peer| peer.id() == "b-c")
        .expect("B dials C");
    assert_eq!(
        Some(b_pays.client_edge_url()),
        b_to_c.endpoint(),
        "the claim-state ask goes to C's own `POST /ilp`, where C answers out of the PEER book \
         that holds this channel (issue #1102)"
    );

    assert!(
        c.pay_channels().is_empty(),
        "C forwards nothing -- it terminates -- so it pays nobody and needs no row. The \
         requirement is keyed on the route, not on the peering."
    );
}

/// **ADR 0042 item 3, enforcing, on the one peering where it can be** (issue
/// #1142 built it; issue #1145 made it safe to turn on).
///
/// `mixed-chain`'s B is the only node in this repository that forwards a
/// packet which arrived from a peer, so its `a-b` row is the only row this
/// setting binds on anywhere -- and therefore the only place the enforcing
/// path is exercised against a running image at all.
///
/// The arithmetic is what makes it survivable, and it is held here because no
/// container can see it: the rule charges against the packet's **own amount**
/// on arrival, A covers `amount_after_fee(A.price, A.fee)`, and those are the
/// same number by construction. A fee edit on A that forgot this row would
/// leave every crossing refused `F06`.
#[test]
fn the_mixed_chain_forwarded_arrival_is_enforced() {
    let a = load("local/mixed-chain/connector-a.toml", MIXED_A);
    let b = load("local/mixed-chain/connector-b.toml", MIXED_B);

    let from_a = b
        .peers()
        .iter()
        .find(|peer| peer.id() == "a-b")
        .expect("B accepts the a-b peering");
    assert_eq!(
        from_a.forwarded_claim_enforcement(),
        connector_config::ForwardedClaimEnforcement::Enforce,
        "the one row in this repository where `forwarded_claim_enforcement` does anything. It \
         defaults to `observe`, which admits-and-logs an uncovered forwarded arrival -- and an \
         observing peering carrying traffic for free is indistinguishable from a paid one in \
         the packet's own answer, which is exactly what this topology's money check exists to \
         rule out."
    );

    let to_b = &a.peer_routes()[0];
    let onward = &b.peer_routes()[0];
    assert_eq!(
        flat(to_b.price()) - fee_of(&a, to_b),
        flat(onward.price()),
        "what A covers on the crossing is `amount_after_fee(price, fee)`, and what B charges the \
         arrival against is the amount that arrives -- the same figure. Enforcing is only safe \
         while those two agree, and nothing at runtime can notice when they stop."
    );

    let b_to_c = b
        .peers()
        .iter()
        .find(|peer| peer.id() == "b-c")
        .expect("B dials C");
    assert_eq!(
        b_to_c.forwarded_claim_enforcement(),
        connector_config::ForwardedClaimEnforcement::Observe,
        "left at the default, and it does nothing either way: C terminates, so no arrival from \
         B is ever a forwarded one"
    );
}

/// **The carriage each peering rides, pinned** (issue #1155).
///
/// No shipped image had ever carried a packet over BTP: all three topologies
/// were ILP-over-HTTP end to end, so ADR 0027's first carriage was proven by
/// `connector-peer-btp`'s in-process suites and by nothing else. `mixed-chain`
/// now runs `a-b` over BTP and leaves `b-c` on HTTP, which is the allocation
/// this test exists to hold -- and it is an allocation, not a preference:
///
/// * `a-b` is the only peering in this repository whose arrival is
///   **forwarded**, and the only row where `forwarded_claim_enforcement`
///   binds, so it is where a carriage has to move a covering claim through a
///   gate that will refuse the packet without one rather than merely move
///   bytes.
/// * `b-c` staying on HTTP is what makes this stack mixed-**carriage** as well
///   as mixed-**chain**, which is the property `CONTEXT.md` asserts: one
///   pipeline below the transport port, a PREPARE indistinguishable by the
///   wire it arrived on. Both peerings on BTP would prove the carriage and
///   lose the comparison.
/// * `two-hop` staying on HTTP keeps the priced peer termination proven on the
///   carriage it is already proven on, and keeps it the containerised
///   counterpart of `two_connectors_peer.rs`, which it diverges from in
///   exactly one deliberate place today.
///
/// **`peer_expose` still defaults to `Neither`, and this test must never be
/// read as pressure to change that.** Say nothing and a node opens no peer
/// listener at all; a peer listener is the surface that accepts value-bearing
/// traffic, and closed-by-default is correct. Carriage is operator policy,
/// never a protocol constant -- what is pinned here is what these topologies
/// *run*.
#[test]
fn the_local_topologies_run_both_carriages_and_not_by_accident() {
    let solo = load("local/solo/connector.toml", SOLO_CONFIG);
    let two_hop_a = load("local/two-hop/connector-a.toml", TWO_HOP_A);
    let two_hop_b = load("local/two-hop/connector-b.toml", TWO_HOP_B);
    let a = load("local/mixed-chain/connector-a.toml", MIXED_A);
    let b = load("local/mixed-chain/connector-b.toml", MIXED_B);
    let c = load("local/mixed-chain/connector-c.toml", MIXED_C);

    // The dial axis: the scheme of each dialing side's `endpoint`, and nothing
    // else, selects the carriage (§2.1). There is no `carriage` key to read.
    assert_eq!(
        a.peers()[0].dial(),
        Some(connector_config::PeerCarriage::Btp),
        "`mixed-chain`'s a-b is the one peering in this repository a shipped image carries a \
         packet over BTP on. Back on `http://` and ADR 0027's first carriage is again proven \
         only in-process."
    );
    let b_to_c = b
        .peers()
        .iter()
        .find(|peer| peer.id() == "b-c")
        .expect("B dials C");
    assert_eq!(
        b_to_c.dial(),
        Some(connector_config::PeerCarriage::Http),
        "b-c stays ILP-over-HTTP so that ONE packet crosses both carriages. This is the half of \
         the pair that would be silently lost by 'converting the topology to BTP'."
    );
    assert_eq!(
        two_hop_a.peers()[0].dial(),
        Some(connector_config::PeerCarriage::Http),
        "two-hop is left alone: it is where a PRICED peer termination is proven, and moving it \
         would give it a second divergence from `two_connectors_peer.rs`"
    );

    // The expose axis, which is per CONNECTOR and answers a different
    // question. B is the node that makes the two axes visibly independent: it
    // exposes BTP and dials HTTP, in one file, with no key pairing them.
    assert_eq!(
        b.peer_expose(),
        connector_config::PeerExposure::Btp,
        "B accepts A over BTP. Not `Both`: an ILP-over-HTTP peer listener here would be a \
         value-bearing surface no configured peer would ever reach -- and it is the absence of \
         one that makes an accepted peer claim in B's journal evidence of the CARRIAGE, since \
         there is nothing else mounted that could have accepted it."
    );
    assert_eq!(
        c.peer_expose(),
        connector_config::PeerExposure::Http,
        "C is dialled over HTTP, so HTTP is what it exposes. Two nodes in one stack exposing \
         different carriages is §2.1 working, not drift."
    );
    assert_eq!(
        two_hop_b.peer_expose(),
        connector_config::PeerExposure::Http,
        "two-hop's payee is dialled over HTTP"
    );
    assert_eq!(
        solo.peer_expose(),
        connector_config::PeerExposure::Neither,
        "THE DEFAULT, AND IT MUST STAY THE DEFAULT. `solo` has no `[[peers]]` at all and writes \
         no `peer_expose`, so it is also the assertion that saying nothing opens no peer \
         listener. Issue #1155 changed what two topologies RUN; it deliberately did not touch \
         what a config that says nothing gets."
    );

    // Both carriages are plaintext here, and the same node-wide opt-in covers
    // both: `Config::plaintext_peerings` matches `ws` and `http` alike, and a
    // websocket that was never wrapped in TLS carries claims and credentials
    // in the clear exactly as an unwrapped POST does.
    let named: Vec<&str> = a.plaintext_peerings().map(|(id, _)| id).collect();
    assert_eq!(
        named,
        vec!["a-b"],
        "the startup WARN must still name this peering now that it is `ws://` -- the switch is \
         about TLS, not about carriage, and a `ws://` endpoint that slipped past it would be an \
         unwrapped peering nobody was told about"
    );
}

