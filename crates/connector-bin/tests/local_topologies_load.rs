/// What one crossing must advance each payee's channel by, in that payee's own
/// unit.
const DEALING_OWED_AT_B: u64 = 1100;
const DEALING_OWED_AT_C: u64 = 4_350_000;

fn settlement_decimals(settlement: &SettlementConfig) -> u8 {
    match settlement {
        SettlementConfig::Evm(evm) => evm.decimals(),
        SettlementConfig::Solana(solana) => solana.decimals(),
    }
}

/// The two tokens B's peerings deal in: the token of the chain each settles
/// on (#1382 -- a runtime x402 peering's token is read off its own channel
/// binding, whose chain names it).
fn dealing_boundary(b: &Config) -> (AssetId, AssetId) {
    let table = topology("dealing");
    (
        settlement(b, table.peering("a-b").chain).asset(),
        settlement(b, table.peering("b-c").chain).asset(),
    )
}

/// What one crossing forwards across the boundary, computed the way the
/// forwarding path computes it: the rate table `build()` makes, the pair
/// looked up the way `Connector::crossing` does, and the table's fee run
/// through `amount_after_rate_and_fee`.
fn dealing_forwarded_amount(b: &Config) -> u64 {
    let table = topology("dealing");
    let onward = table.route_on("connector-b");
    let rates = SharedRateTable::from_config(b.denomination())
        .expect("a node with a declared rate has a table");
    let (incoming, outgoing) = dealing_boundary(b);
    let rate = rates
        .lookup(&incoming, &outgoing, chrono::Utc::now())
        .rate()
        .expect("a STATIC row never goes stale");
    amount_after_rate_and_fee(onward.price, rate, table.peering("b-c").fee)
        .expect("the converted amount must survive this hop's fee")
}

