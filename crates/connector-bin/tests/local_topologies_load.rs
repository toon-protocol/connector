/// What ADR 0070 says each `anon` sidecar's configuration has to carry: the
/// terms flag, and a hidden service persisted on a named volume -- now on
/// BOTH sides, because each node's self-description is read over a circuit
/// by the other's `POST /peers`. Each targets its connector by a fixed IP,
/// because `anon` resolves that target when it PARSES its config.
