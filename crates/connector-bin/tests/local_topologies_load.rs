/// The rehearsal, and the third copy of every figure in it.
///
/// `--expect-fulfill` is not enough on its own here for `two-hop`'s reason --
/// a peer claim's verdict rides back in `Toon-Claim-Ack` and never gates the
/// packet, so a peering whose every claim was refused still FULFILLs -- and
/// for one this topology adds: a fulfil says nothing about the circuit.
#[test]
fn the_onion_rehearsal_reads_the_payees_own_claim_journal() {
    let payer = load("local/onion/connector-a.toml", ONION_A);
    let payee = load("local/onion/connector-b.toml", ONION_B);
    let sender = onion_service("sender");

    let channel_id = evm_channel(&payer, "a-b").channel_id().to_string();
    assert!(
        sender.contains(&format!("CHANNEL={channel_id}")),
        "the sender must read B's claim journal for the peering's own channel id ({channel_id}), \
         or the rehearsal passes over a peering that carried both packets for free"
    );
    assert!(
        sender.contains("peer-claims.log") && sender.contains("inbound_claim_accepted"),
        "the sender reads the journal line by line rather than grepping for the channel id, \
         because a claim that merely EXISTS proves nothing -- `inbound_claim_accepted` is \
         `connector_runtime::journal`'s own encoding of an accepted claim"
    );

    let price = flat(payee.routes()[0].price());
    let fee = fee_of(&payer, &payer.peer_routes()[0]);
    for (constant, why) in [
        (
            format!("PRICE={price}"),
            "every accepted claim must advance by at least B's committed price",
        ),
        (
            format!("FEE={fee}"),
            "what A kept must equal A's committed fee exactly -- ADR 0010's earnings rule as a \
             measurement on a running image",
        ),
        (
            format!("AMOUNT={}", price + fee),
            "the packet carries the path's COST (`CONTEXT.md`): A's fee plus the price of the \
             route B terminates, with no slack in either direction",
        ),
        (
            "CROSSINGS=2".to_string(),
            "two crossings, because a payer told nonce 0 forever re-signs crossing 1's \
             cumulative amount and one crossing cannot see it (issue #1102)",
        ),
    ] {
        assert!(
            sender.contains(&constant),
            "local/onion/compose.yml's sender must set `{constant}`: {why}. Held here because \
             the two halves live in different files and no container can notice a figure that \
             quietly went to zero."
        );
    }

    assert!(
        sender.contains("--expect-fulfill"),
        "without it a REJECT is reported and the process exits zero -- a green tick over an \
         unpaid, undelivered packet"
    );
    assert!(
        sender.contains("--socks-proxy"),
        "the sender is on A's network, so its `--seal-to` -- B's self-description, whose \
         identity the payload is sealed to (ADR 0018) -- can only be fetched over the circuit. \
         The same host-selected rule applied to two URLs independently (ADR 0070 decision 5): \
         `--operator` names a container on this network and goes direct."
    );
    assert!(
        sender.contains("--dry-run"),
        "the rehearsal must WAIT for a circuit before it asserts on one. `connector send \
         --dry-run` fetches `--seal-to`'s self-description through the proxy and sends no \
         packet, so waiting costs no crossing the money assertion would then have to account \
         for -- and what it gives up on is the run, not the assertion."
    );
    assert!(
        !sender.contains(ONION_PLACEHOLDER),
        "the sender must take B's address from A's RENDERED config rather than from a literal \
         here: the address is generated fresh on every bring-up, and a second copy of it would \
         be one copy too many"
    );
}

